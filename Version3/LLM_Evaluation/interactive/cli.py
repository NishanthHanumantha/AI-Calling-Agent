def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Interactive four-model LLM comparison lab (local, no Twilio).")
    parser.add_argument(
        "--mode",
        choices=["customer", "outbound", "multilingual"],
        default="customer",
        help="customer-first lab, outbound simulation, or multilingual business-conversation benchmark",
    )
    parser.add_argument(
        "--track",
        choices=["english", "hindi", "kannada", "mixed", "all"],
        default="all",
        help="Multilingual language track (used with --mode multilingual)",
    )
    parser.add_argument("--opening", choices=["generated", "fixed"], default="generated", help="Outbound opening: generated by each model, or one fixed line")
    parser.add_argument("--dry-run", action="store_true", help="Validate pipeline; zero API calls")
    parser.add_argument(
        "--check-models",
        action="store_true",
        help="Probe Sarvam Conversational, DeepSeek V4.1 Flash, Claude Sonnet, and Claude Opus",
    )
    parser.add_argument("--demo", action="store_true", help="Run a scripted 5-turn demonstration")
    parser.add_argument("--max-display-chars", type=int, default=0, help="Truncate displayed answers (0 = no limit)")
    parser.add_argument("--verbose", action="store_true")
    return parser.parse_args(argv)


def dry_run_report(session: InteractiveSession) -> str:
    lines = [
        "DRY-RUN VERIFICATION",
        "=" * 60,
        (
            "MODE: OFFLINE / MULTILINGUAL INTERACTIVE EVALUATION"
            if session.language_track
            else "MODE: OFFLINE / OUTBOUND INTERACTIVE EVALUATION"
            if session.conversation_mode == "outbound"
            else "MODE: OFFLINE / INTERACTIVE EVALUATION"
        ),
        "TWILIO: DISABLED",
        f"Configuration loaded: {bool(session.config)}",
        f"System prompt loaded: {bool(session.system_prompt)}",
        f"Golden dataset cases: {len(session.dataset)}",
        f"Retrieved knowledge chars: {len(session.retrieved_context)}",
        f"Session run_id: {session.run_id}",
        "",
        "Models:",
    ]
    for slot in session.slots:
        thinking = (slot.runtime or {}).get("thinking_mode")
        thinking_note = f" / thinking={thinking}" if thinking else ""
        lines.append(
            f"  {slot.alias}: {slot.provider} / {slot.model_id or '(missing id)'} / {slot.status}{thinking_note}"
        )
    sample = "Where is it located?"
    if session.language_track:
        sample = track_utterances(session.language_track)[0]
        lines.append(f"Language track: {session.language_track}")
    payloads = session.preview_payloads(sample)
    first = next(iter(payloads.values()))
    same_kb = all(session.retrieved_context in text for text in payloads.values())
    same_user = all(sample in text for text in payloads.values())
    lines += [
        "",
        f"Prompt construction OK: {bool(first)}",
        f"Same user message in all payloads: {same_user}",
        f"Same knowledge context in all payloads: {same_kb}",
        f"Command parse /help: {parse_command('/help')}",
        f"Command parse customer text: {parse_command('Hello')}",
    ]
    if session.conversation_mode == "outbound":
        opening = session.begin_outbound()
        lines.append(f"Opening mode: {session.opening_mode}")
        lines.append(f"Opening responses: {len(opening)}")
        if session.opening_mode == "fixed":
            texts = [resp.answer for resp in opening]
            lines.append(f"Fixed opening identical: {len(set(texts)) == 1}")
    session.generate_turn(sample)
    ev = session.evaluate_latest()
    export_dir = session.export()
    lines += [
        f"Evaluation pipeline OK: {ev is not None}",
        f"Export pipeline OK: {export_dir.exists()}",
        f"Export dir: {export_dir}",
        "API calls made: 0",
        "=" * 60,
    ]
    return "\n".join(lines)


def _session_from_args(args, *, language_track: str | None = None, providers=None) -> InteractiveSession:
    mode = args.mode
    if mode == "multilingual":
        mode = "outbound"
    return InteractiveSession(
        dry_run=args.dry_run,
        max_display_chars=args.max_display_chars,
        conversation_mode=mode,
        opening_mode=args.opening,
        language_track=language_track,
        providers=providers,
    )


def selected_tracks(track: str) -> tuple[str, ...]:
    if track == "all":
        return LANGUAGE_TRACKS
    return (track,)


def play_multilingual_track(session: InteractiveSession, track: str, out=None) -> None:
    if session.language_track != track:
        session.language_track = track
    if not any(turn.get("kind") == "opening" for turn in session.turns):
        opening = session.begin_outbound()
        if out:
            out(render_outbound_opening(opening, session.max_display_chars))
    for utterance in track_utterances(track):
        if out:
            out(f"Customer > {utterance}")
            out(
                f"Waiting for 4 models (bounded timeout {session.collect_deadline_seconds():.0f}s, "
                f"language_track={session.language_track})..."
            )
        responses = session.generate_turn(utterance)
        if out:
            out(render_turn(session.turns[-1]["index"], utterance, responses, session.max_display_chars, OUTBOUND_NAMES))


def run_multilingual_tracks(args, out, providers=None) -> int:
    tracks = selected_tracks(args.track)
    per_track = {}
    export_roots = []
    out("=" * 60)
    out("MULTILINGUAL BENCHMARK — evaluation only. Twilio DISABLED.")
    out(f"Track order: {' -> '.join(tracks)}")
    out("=" * 60)
    for track in tracks:
        out("")
        out(f"Track: {TRACK_LABELS[track]} ({track})")
        out(f"Setting language_track = {track}")
        session = _session_from_args(args, language_track=track, providers=providers)
        if session.language_track != track:
            raise RuntimeError(f"language_track was not applied: expected {track}, got {session.language_track}")
        out(banner("multilingual", session.opening_mode, track))
        play_multilingual_track(session, track, out)
        coverage = session.evaluate_session()
        if session.evaluations:
            out(render_session_summary(session.evaluations))
            out(render_coverage(coverage))
        export_dir = session.export()
        export_roots.append(export_dir)
        out(f"Track export: {export_dir}")
        out(f"Completed language_track = {track}")
        per_track[track] = session_summary(session.evaluations)
    aggregate = aggregate_multilingual(per_track)
    parent = export_roots[0].parent if export_roots else Path("LLM_Evaluation/output/interactive_runs")
    agg_path = write_multilingual_aggregate(parent / f"multilingual_aggregate_{tracks[0] if len(tracks)==1 else 'all'}.json", aggregate)
    out("")
    out(f"Multilingual aggregate: {agg_path}")
    out("No model ranking. Evidence only.")
    return 0


def multilingual_dry_run_report(args, out) -> int:
    tracks = selected_tracks(args.track)
    for track in tracks:
        session = _session_from_args(args, language_track=track)
        out(dry_run_report(session))
        out(f"Track {track} dry-run API calls made: 0")
    return 0



def handle_command(session: InteractiveSession, command: str, arg: str, out) -> bool:
    if command in {"/help"}:
        out(help_text())
    elif command == "/reset":
        session.reset()
        if session.conversation_mode == "outbound":
            opening = session.begin_outbound()
            out(render_outbound_opening(opening, session.max_display_chars))
            out("Outbound conversation reset.")
        else:
            out("Conversation reset. Next message is TURN 01.")
    elif command == "/history":
        out(render_history(session.turns))
    elif command == "/evaluate":
        if arg.lower() == "session":
            if not session.turns:
                out("No turns to evaluate.")
            else:
                coverage = session.evaluate_session()
                out(render_session_summary(session.evaluations))
                out(render_coverage(coverage))
        else:
            ev = session.evaluate_latest()
            if ev is None:
                out("No turns to evaluate.")
            else:
                out(render_evaluation(ev))
    elif command in {"/save", "/export"}:
        path = session.export()
        out(f"Saved session to {path}")
    elif command == "/models":
        out(render_models(session.slots))
    elif command == "/status":
        last = session.turns[-1]["responses"] if session.turns else None
        responses = [TurnResponse(**item) for item in last] if last else None
        out(render_status(session.slots, responses))
    elif command == "/debug":
        out(render_debug(session.last_debug or {"note": "No turn yet."}))
    elif command == "/quit":
        return False
    else:
        out(f"Unknown command: {command}. Type /help")
    return True


def run_demo(session: InteractiveSession, out) -> None:
    outbound = session.conversation_mode == "outbound"
    multilingual = bool(session.language_track)
    out("=" * 60)
    if multilingual:
        out("DEMO MODE — multilingual scripted comparison. Not a phone call.")
    elif outbound:
        out("DEMO MODE — outbound baseline. Not a phone call.")
    else:
        out("DEMO MODE — scripted comparison. Not a phone call.")
    out("TWILIO: DISABLED")
    out("=" * 60)
    out(banner(session.conversation_mode, session.opening_mode, session.language_track))
    if multilingual:
        play_multilingual_track(session, session.language_track, out)
        coverage = session.evaluate_session()
        if session.evaluations:
            out(render_evaluation(session.evaluations[-1]))
            out(render_session_summary(session.evaluations))
            out(render_coverage(coverage))
        path = session.export()
        out(f"Demo export: {path}")
        return
    turns = OUTBOUND_BASELINE if outbound else DEMO_TURNS
    names = OUTBOUND_NAMES if outbound else None
    if outbound:
        opening = session.begin_outbound()
        out(render_outbound_opening(opening, session.max_display_chars))
    for utterance in turns:
        out(f"Customer > {utterance}")
        responses = session.generate_turn(utterance)
        out(render_turn(session.turns[-1]["index"], utterance, responses, session.max_display_chars, names))
    coverage = session.evaluate_session()
    if session.evaluations:
        out(render_evaluation(session.evaluations[-1]))
        out(render_session_summary(session.evaluations))
        out(render_coverage(coverage))
    path = session.export()
    out(f"Demo export: {path}")


def _read_loop(session: InteractiveSession, out, stdin=None, names=None) -> int:
    stream = stdin or sys.stdin
    while True:
        try:
            out("Customer > ", end="")
            line = stream.readline()
            if line == "":
                break
            raw = line.strip()
        except (EOFError, KeyboardInterrupt):
            out("\nExiting.")
            break
        if not raw:
            continue
        command, arg = parse_command(raw)
        if command:
            if not handle_command(session, command, arg, out):
                out("Goodbye.")
                break
            continue
        responses = session.generate_turn(raw)
        out(render_turn(session.turns[-1]["index"], raw, responses, session.max_display_chars, names))
    return 0


def interactive_loop(session: InteractiveSession, out, stdin=None) -> int:
    out(banner())
    return _read_loop(session, out, stdin)


def outbound_loop(session: InteractiveSession, out, stdin=None) -> int:
    out(banner("outbound", session.opening_mode))
    opening = session.begin_outbound()
    out(render_outbound_opening(opening, session.max_display_chars))
    return _read_loop(session, out, stdin, OUTBOUND_NAMES)


class Printer:
    def __init__(self, sink=None):
        self.sink = sink or sys.stdout

    def __call__(self, text: str = "", end: str = "\n") -> None:
        self.sink.write(text + end)
        self.sink.flush()


def multilingual_loop(session: InteractiveSession, out, stdin=None) -> int:
    out(banner("multilingual", session.opening_mode, session.language_track))
    opening = session.begin_outbound()
    out(render_outbound_opening(opening, session.max_display_chars))
    return _read_loop(session, out, stdin, OUTBOUND_NAMES)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(asctime)s %(levelname)s %(message)s",
    )
    out = Printer()
    if args.mode == "multilingual":
        if args.check_models:
            session = _session_from_args(args, language_track="english")
            out(format_check_report(session.check_models()))
            return 0
        if args.dry_run and not args.demo:
            return multilingual_dry_run_report(args, out)
        if args.demo or args.track == "all":
            return run_multilingual_tracks(args, out)
        session = _session_from_args(args, language_track=args.track)
        return multilingual_loop(session, out)
    session = InteractiveSession(
        dry_run=args.dry_run,
        max_display_chars=args.max_display_chars,
        conversation_mode=args.mode,
        opening_mode=args.opening,
    )
    if args.check_models:
        result = session.check_models()
        out(format_check_report(result))
        return 0
    if args.dry_run and not args.demo:
        out(dry_run_report(session))
        return 0
    if args.demo:
        run_demo(session, out)
        return 0
    if session.conversation_mode == "outbound":
        return outbound_loop(session, out)
    return interactive_loop(session, out)


if __name__ == "__main__":
    raise SystemExit(main())
